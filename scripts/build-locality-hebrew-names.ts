/** Regenerate from retained official sources:
 * python3 -m pip install --target .backup-scratch/python xlrd==2.0.2 openpyxl==3.1.5
 * PYTHONPATH=.backup-scratch/python node scripts/build-locality-hebrew-names.ts
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { isEnvelopeRow, type LocalityDataset } from '../src/data/schema.ts';
import { resolveLocalityHebrew, type CbsNameRecord, type LocalityNames } from '../src/data/locality-names.ts';
const python = spawnSync('python3', ['scripts/locality-map-cbs.py'], { encoding: 'utf8', maxBuffer: 10_000_000 });
if (python.status !== 0) throw new Error(python.stderr);
const records = JSON.parse(python.stdout) as CbsNameRecord[];
const summary: string[] = [];
const conflicts: string[] = [];
for (const file of readdirSync('public/data').filter(f => /^k\d+-localities.json$/.test(f)).sort()) {
  const data = JSON.parse(readFileSync(`public/data/${file}`, 'utf8')) as LocalityDataset;
  const election = JSON.parse(readFileSync(`public/data/${data.id}.json`, 'utf8'));
  const path = `public/data/${data.id}-locality-names.json`;
  const names = JSON.parse(readFileSync(path, 'utf8')) as LocalityNames;
  names.hebrew = data.rows.map(row => isEnvelopeRow(row) ? { name: row.nameHe, source: 'cec' } : resolveLocalityHebrew(row, Number(election.electionDate.slice(0, 4)), records));
  let changed = 0, cbs = 0, repaired = 0, truncation = 0, spelling = 0, renames = 0, other = 0, missing = 0;
  data.rows.forEach((row, i) => {
    if (isEnvelopeRow(row)) return;
    const resolved = names.hebrew![i];
    if (resolved.name !== row.nameHe) changed++;
    if (resolved.source === 'cbs') cbs++;
    if (resolved.parenthesesRepaired) repaired++;
    if (resolved.reason === 'truncation') truncation++;
    if (resolved.reason === 'spelling') spelling++;
    if (resolved.reason === 'rename-merger') renames++;
    if (resolved.reason === 'other' || resolved.reason === 'no-cbs') other++;
    if (resolved.reason === 'no-cbs') missing++;
    if (resolved.conflict) {
      conflicts.push(`| ${data.id} | ${i} | ${row.code} | ${row.nameHe} | ${resolved.conflict} | ${resolved.year} | ${resolved.reason} | ${resolved.truncated ? 'yes' : ''} |`);
    }
  });
  summary.push(`| ${data.id} | ${changed} | ${cbs} | ${repaired} | ${truncation} | ${spelling} | ${renames} | ${other} | ${missing} |`);
  writeFileSync(path, JSON.stringify(names) + '\n');
}
