/** Regenerate from retained official sources:
 * python3 -m pip install --target .backup-scratch/python xlrd==2.0.2 openpyxl==3.1.5
 * PYTHONPATH=.backup-scratch/python node scripts/build-locality-hebrew-names.ts
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { isEnvelopeRow, type LocalityDataset } from '../src/data/schema.ts';
import { resolveLocalityHebrew, type CbsNameRecord, type LocalityNames } from '../src/data/locality-names.ts';
const python = spawnSync('python3', ['scripts/locality-map-cbs.py'], { encoding: 'utf8', maxBuffer: 10_000_000 });
if (python.status !== 0) throw new Error(python.stderr);
const records = JSON.parse(python.stdout) as CbsNameRecord[];
const summary: string[] = [];
const conflicts: string[] = [];
for (const file of readdirSync('public/data').filter(f => /^k\d+-localities.json$/.test(f)).sort()) {
  const data = JSON.parse(readFileSync(`public/data/${file}`, 'utf8')) as LocalityDataset;
  const election = JSON.parse(readFileSync(`public/data/${data.id}.json`, 'utf8'));
  const path = `public/data/${data.id}-locality-names.json`;
  const names = JSON.parse(readFileSync(path, 'utf8')) as LocalityNames;
  names.hebrew = data.rows.map(row => isEnvelopeRow(row) ? { name: row.nameHe, source: 'cec' } : resolveLocalityHebrew(row, Number(election.electionDate.slice(0, 4)), records));
  let changed = 0, cbs = 0, retained = 0;
  data.rows.forEach((row, i) => {
    if (isEnvelopeRow(row)) return;
    const resolved = names.hebrew![i];
    if (resolved.name !== row.nameHe) changed++;
    if (resolved.source === 'cbs') cbs++;
    if (resolved.conflict) {
      retained++;
      conflicts.push(`| ${data.id} | ${i} | ${row.code} | ${row.nameHe} | ${resolved.conflict} | ${resolved.year} |`);
    }
  });
  summary.push(`| ${data.id} | ${changed} | ${cbs} | ${retained} |`);
  writeFileSync(path, JSON.stringify(names) + '\n');
}
writeFileSync('docs/research/locality-hebrew-names.md', `# Hebrew locality display names

Generated by \`scripts/build-locality-hebrew-names.ts\`; regeneration instructions are in that script.
Inputs: retained official CEC election rows in \`public/data/k*-localities.json\` and official CBS lists in \`data/raw/demographics/cbs-*\` (2003–2024), parsed by \`scripts/locality-map-cbs.py\`. Source URLs and provenance remain in the repository's retained source manifests. No external or inferred names.

Policy: code-only join, nearest CBS year, earlier on ties. Remove CBS footnote asterisks. Only punctuation and whitespace may differ for substitution; every letter difference, including spelling variants, truncation and historical renaming, keeps CEC. No code means no CBS substitution. CEC fallback only collapses whitespace and inserts a space before an opening parenthesis. Original CEC rows remain untouched, searchable, and disclosed in name tooltips. Counts exclude envelopes; changed compares the displayed name with the exact CEC string.

| Election | Changed | CBS names | Letter conflicts kept as CEC |
| --- | ---: | ---: | ---: |
${summary.join('\n')}

Every non-formatting difference follows (row indices are zero-based). These are unresolved name conflicts, not proof that the code denotes a different locality. The CBS year is the closest retained edition, not necessarily the election year. In particular the k25 Tarabin export loses letters compared with CBS; it remains CEC rather than silently reconstructing them.

| Election | Row | Code | Original CEC (retained) | Proposed CBS (not substituted) | CBS year |
| --- | ---: | ---: | --- | --- | ---: |
${conflicts.join('\n')}
`);
