import re
TITLES = ['ד"ר','דר','הרב','פרופ','פרופסור','עו"ד','עוד','רו"ח','אדריכל','אדר','ח"כ','גב','מר','השיח','שיח','תא"ל','אל"מ','סא"ל','רס"ן','אלוף','ניצב','תת-ניצב','ד״ר','עו״ד','רו״ח','ח״כ','תא״ל','אל״מ','סא״ל','רס״ן','מהנדס','מהנדסת','אינג','הרבנית','ראש','מועצה']
FINAL = str.maketrans('ךםןףץ', 'כמנפצ')
def clean(s):
    s = s or ''
    s = s.replace('״','"').replace('׳',"'").replace('’',"'").replace('`',"'")
    s = re.sub(r'\([^)]*\)', ' ', s)  # drop parenthesised earlier names for the base form
    s = re.sub(r'[-־–—_.,/]', ' ', s)
    toks = [t for t in s.split() if t]
    out = []
    for t in toks:
        tt = t.strip('"\'')
        if t in TITLES or tt in ('דר','הרב','פרופ','עוד','רוח','חכ','גב','מר','אינג','תאל','אלמ','סאל','רסן') or t.rstrip("'") in ('פרופ','אינג','גב','דר'):
            continue
        out.append(t)
    return out
def paren(s):
    return re.findall(r'\(([^)]*)\)', s or '')
def norm_tok(t):
    t = t.translate(FINAL).replace('"','').replace("'",'')
    return t
def skel(t):
    # loose: drop vowel letters ו י א (not first letter) and doubled letters
    t = norm_tok(t)
    if not t: return t
    head, rest = t[0], re.sub('[ויא]', '', t[1:])
    r = head + rest
    r = re.sub(r'(.)\1+', r'\1', r)
    return r
