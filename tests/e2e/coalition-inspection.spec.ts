import { expect, test } from '@playwright/test';
import { choose } from './choices.ts';
for (const lang of ['en', 'he']) for (const theme of ['light', 'dark']) for (const width of [1500, 1024, 390]) {
  test(`coalition inspection and scenario flow ${lang} ${theme} ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 });
    await page.addInitScript(({lang, theme}) => localStorage.setItem('israel-elections:v1', ((o: { theme?: string; hintDismissed?: boolean; [k: string]: unknown }) => { if (!sessionStorage.getItem('seeded-settings')) sessionStorage.setItem('seeded-settings', '1'), localStorage.setItem('israel-elections:settings', JSON.stringify({ v: 2, values: { ...(o.theme ? { theme: o.theme } : {}), ...(o.hintDismissed ? { starterTip: false } : {}), decimals: 2 } })); return JSON.stringify(o); })({ lang, theme, level: 'expert', hintDismissed: true })), {lang, theme});
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    const api: string[] = []; page.on('request', r => { if (r.url().includes('api.github.com')) api.push(r.url()); });
    await page.goto('/');
    for (const election of ['k26', 'k25', 'k14', 'k12', 'k1']) {
      await choose(page.getByRole('button', { name: lang === 'he' ? 'בחירות' : 'Election', exact: true }), election);
      await page.getByRole('tab', { name: lang === 'he' ? 'קואליציות' : 'Coalitions', exact: true }).click();
      await expect(page.locator('.coal-now')).toHaveCount(0);
      const options = page.locator('.coal-list > li:not(.coal-detail)');
      await expect(options.first()).toBeVisible();
      const count = await options.count(); expect(count).toBeGreaterThan(1);
      await options.first().getByRole('button').scrollIntoViewIfNeeded();
      const scrollBefore = await page.evaluate(() => scrollY);
      await options.first().getByRole('button').click();
      await expect.poll(() => page.evaluate(() => scrollY)).toBe(scrollBefore);
      await expect(options).toHaveCount(count);
      expect(await page.locator('.coal-names').evaluateAll(nodes => nodes.every(el => el.scrollWidth <= el.clientWidth + 1))).toBe(true);
      await expect(page.locator('.coal-choice button[aria-pressed="true"]')).toHaveText(Array(await page.locator('.coal-choice').count()).fill(lang === 'he' ? 'כל אפשרות' : 'Any'));
      await expect(page.locator('.coal-detail .coal-partners li')).not.toHaveCount(0);
      await options.nth(1).getByRole('button').focus(); await page.keyboard.press('Enter');
      await expect(options.nth(1).getByRole('button')).toHaveAttribute('aria-pressed', 'true');
      await expect(options).toHaveCount(count);
      await page.screenshot({ path: `.backup-scratch/feedback-f/after-coalitions-${election}-${lang}-${theme}-${width}.png`, fullPage: true });
      await page.locator('.coal-detail').getByRole('button', { name: lang === 'he' ? 'סגירה' : 'Close', exact: true }).click();
      await expect(page.locator('.coal-detail')).toHaveCount(0);
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await page.getByRole('tab', { name: lang === 'he' ? 'תרחישים' : 'Scenarios', exact: true }).click();
      const nameBox = await page.getByRole('textbox', { name: lang === 'he' ? 'שם' : 'Name', exact: true }).boundingBox();
      const descriptionBox = await page.getByRole('textbox', { name: lang === 'he' ? 'תיאור' : 'Description', exact: true }).boundingBox();
      expect(nameBox!.height).toBe(descriptionBox!.height);
      if (width > 760) expect(nameBox!.y).toBe(descriptionBox!.y);
      await page.screenshot({ path: `.backup-scratch/feedback-f/after-scenarios-${election}-${lang}-${theme}-${width}.png`, fullPage: true });
    }
    await page.getByRole('tab', { name: lang === 'he' ? 'תרחישים' : 'Scenarios', exact: true }).click();
    await expect(page.locator('.scenario-gallery [role="status"]')).not.toContainText(lang === 'he' ? 'טוען…' : 'Loading…');
    expect(api).toEqual([]);
    await page.screenshot({ path: `.backup-scratch/feedback-f/after-scenarios-${lang}-${theme}-${width}.png`, fullPage: true });
    await page.locator('.scn-options summary').click();
    await expect(page.getByRole('combobox', { name: lang === 'he' ? 'צבע התרחיש' : 'Scenario colour', exact: true })).toBeVisible();
    expect((await page.getByRole('combobox', { name: lang === 'he' ? 'צבע התרחיש' : 'Scenario colour', exact: true }).boundingBox())!.width).toBeLessThanOrEqual(280);
    await page.locator('.sg-publish-disclosure summary').click();
    await expect(page.locator('.sg-publish')).toBeVisible();
    expect(errors).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  });
}
test('filters remain unchanged when inspecting and community index drives search and publishing', async ({ page, baseURL }) => {
  await page.addInitScript(() => localStorage.setItem('israel-elections:v1', ((o: { theme?: string; hintDismissed?: boolean; [k: string]: unknown }) => { if (!sessionStorage.getItem('seeded-settings')) sessionStorage.setItem('seeded-settings', '1'), localStorage.setItem('israel-elections:settings', JSON.stringify({ v: 2, values: { ...(o.theme ? { theme: o.theme } : {}), ...(o.hintDismissed ? { starterTip: false } : {}), decimals: 2 } })); return JSON.stringify(o); })({ lang: 'en', level: 'expert', hintDismissed: true })));
  await page.route('**/data/scenarios.json', route => route.fulfill({ json: { timestamp: Date.now(), entries: [{ name: 'Turnout trial', description: 'More voters', electionId: 'k25', year: '2022', tags: ['turnout'], shareLink: `${baseURL}/#s=abc`, issue: 1, author: 'example', date: '2026-01-01', likes: 2 }] } }));
  await page.goto('/');
  await page.getByRole('tab', { name: 'Coalitions', exact: true }).click();
  await page.locator('.coal-choice').first().getByRole('button', { name: 'Any', exact: true }).click();
  await expect(page.locator('.session')).toContainText('No changes yet');
  await expect(page.locator('.band').getByRole('button', { name: 'Undo', exact: true })).toBeDisabled();
  await page.locator('.coal-choice').first().getByRole('button', { name: 'In', exact: true }).click();
  const edited = await page.locator('.session').innerText();
  await page.locator('.coal-choice').first().getByRole('button', { name: 'In', exact: true }).click();
  await expect(page.locator('.session')).toHaveText(edited, { useInnerText: true });
  const count = await page.locator('.coal-list > li').count();
  await page.locator('.coal-list button').first().click();
  await expect(page.locator('.coal-list > li:not(.coal-detail)')).toHaveCount(count);
  await expect(page.locator('.coal-choice').first().getByRole('button', { name: 'In', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.locator('.coal-detail').getByRole('button', { name: 'Close', exact: true }).click();
  await expect(page.locator('.coal-choice').first().getByRole('button', { name: 'In', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.coal-head').getByRole('button', { name: 'Official coalition', exact: true })).toHaveCount(0);
  await page.locator('.coal-head').getByRole('button', { name: 'Clear the coalition', exact: true }).click();
  await expect(page.locator('.coal-now')).toHaveCount(0);
  const preset = page.locator('.coal > .row').nth(1).getByRole('button').first();
  await preset.click();
  const presetHistory = await page.locator('.session').innerText();
  await preset.click();
  await expect(page.locator('.session')).toHaveText(presetHistory, { useInnerText: true });
  await page.getByRole('tab', { name: 'Scenarios', exact: true }).click();
  await expect(page.locator('.scenario-gallery .scn-card')).toContainText('Turnout trial');
  await page.getByRole('searchbox').fill('no matches');
  await expect(page.locator('.scenario-gallery')).toContainText('No matches. Clear your search or filters.');
  await page.getByRole('searchbox').fill('turnout');
  await expect(page.locator('.scenario-gallery .scn-card')).toHaveCount(1);
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Publish trial');
  await page.getByRole('textbox', { name: 'Name', exact: true }).press('Tab');
  await page.getByRole('button', { name: 'Copy a share link', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Share link', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Description', exact: true }).fill('Updated description');
  await page.getByRole('textbox', { name: 'Description', exact: true }).press('Tab');
  await expect(page.getByRole('textbox', { name: 'Share link', exact: true })).toHaveCount(0);
  await page.locator('.sg-publish-disclosure summary').click();
  // Inspect the prefilled issue URL without submitting anything to GitHub.
  await page.evaluate(() => { window.open = (() => ({ opener: null, location: { set href(value: string) { (window as unknown as { published: string }).published = value; } }, close() {} })) as unknown as typeof window.open; });
  await page.getByRole('button', { name: 'Publish on GitHub ↗', exact: true }).click();
  await expect.poll(() => page.evaluate(() => (window as unknown as { published?: string }).published)).toContain('github.com/YiftahCooper/israel-elections/issues/new?');
  expect(await page.evaluate(() => new URL((window as unknown as { published: string }).published).searchParams.get('title'))).toBe('Publish trial');
});
